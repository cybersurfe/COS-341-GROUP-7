import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.concurrent.TimeUnit;

/*
runs the hand-written regression suite in tests/ok and tests/bad (generated by tests/gen_cases.py).
  tests/ok/NAME.spl  must compile, the generated C++ must build with g++ -Wall -Wextra -pedantic WITHOUT any warning
                     of the kinds that point at real mistakes, and its output must equal NAME.out exactly
  tests/bad/NAME.spl must be rejected; NAME.err holds "phase|fragment": the error must come from that phase and
                     its message must contain the fragment (and, except for type conflicts, a line/column)
usage: java SuiteTest [testsDir]
*/
public final class SuiteTest {
    public static void main(String[] args) throws Exception {
        Path dir = Paths.get(args.length > 0 ? args[0] : "tests");
        Path tmp = Files.createTempDirectory("suite");
        int bad = 0, n = 0;
        //big stack, like the compiler's own main thread
        final int[] result = new int[2];
        Thread t = new Thread(null, () -> {
            try { run(dir, tmp, result); } catch (Exception e) { e.printStackTrace(); result[0]++; }
        }, "suite", 1L << 29);
        t.start();
        t.join();
        System.out.println(result[0] == 0 ? "SUITE PASSED (" + result[1] + " tests)" : "SUITE FAILED: " + result[0] + " of " + result[1]);
        System.exit(result[0] == 0 ? 0 : 1);
    }

    private static void run(Path dir, Path tmp, int[] result) throws Exception {
        List<File> oks = list(dir.resolve("ok"), ".spl"), bads = list(dir.resolve("bad"), ".spl");
        for (File f : oks) {
            result[1]++;
            String name = f.getName().replace(".spl", "");
            String src = new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8);
            String expected = new String(Files.readAllBytes(dir.resolve("ok").resolve(name + ".out")), StandardCharsets.UTF_8);
            try {
                Compiler.Output o = Compiler.compile(src);
                Path cpp = tmp.resolve(name + ".cpp"), bin = tmp.resolve(name + ".bin");
                Files.write(cpp, o.cpp.getBytes(StandardCharsets.UTF_8));
                String cc = exec(60, null, "g++", "-std=c++11", "-Wall", "-Wextra", "-pedantic", cpp.toString(), "-o", bin.toString());
                if (!Files.exists(bin)) { fail(result, name, "g++ failed:\n" + cc); continue; }
                //unused variables / labels are expected noise of generated code; anything else is a real finding
                String serious = filterWarnings(cc);
                if (!serious.isEmpty()) { fail(result, name, "g++ warnings:\n" + serious); continue; }
                String out = exec(20, null, bin.toString());
                if (!out.equals(expected)) fail(result, name, "expected '" + expected + "' but got '" + out + "'");
                else System.out.println("ok   " + name);
            } catch (Compiler.CompileException e) {
                fail(result, name, "valid program rejected (" + e.phase + "): " + e.getMessage());
            }
        }
        for (File f : bads) {
            result[1]++;
            String name = f.getName().replace(".spl", "");
            String src = new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8);
            String[] want = new String(Files.readAllBytes(dir.resolve("bad").resolve(name + ".err")), StandardCharsets.UTF_8).trim().split("\\|", 2);
            try {
                Compiler.compile(src);
                fail(result, name, "invalid program was ACCEPTED");
            } catch (Compiler.CompileException e) {
                boolean locOk = e.getMessage().matches("(?s).*line \\d+, column \\d+.*") || e.getMessage().contains("float-integer-conflict");
                if (!e.phase.equals(want[0])) fail(result, name, "wrong phase " + e.phase + " (wanted " + want[0] + "): " + e.getMessage());
                else if (!e.getMessage().contains(want[1])) fail(result, name, "message lacks '" + want[1] + "': " + e.getMessage());
                else if (!locOk) fail(result, name, "no line/column in: " + e.getMessage());
                else System.out.println("ok   " + name + "  ->  " + e.getMessage().split("\n")[0]);
            }
        }
    }

    private static String filterWarnings(String cc) {
        StringBuilder sb = new StringBuilder();
        for (String line : cc.split("\n")) {
            if (!line.contains("warning:")) continue;
            if (line.contains("-Wunused-variable") || line.contains("-Wunused-label") || line.contains("-Wunused-but-set-variable")
                || line.contains("-Wunused-value")) continue;
            sb.append(line).append("\n");
        }
        return sb.toString();
    }

    private static void fail(int[] result, String name, String why) {
        result[0]++;
        System.out.println("FAIL " + name + "\n     " + why.replace("\n", "\n     "));
    }

    private static List<File> list(Path d, String ext) {
        List<File> out = new ArrayList<>();
        File[] fs = d.toFile().listFiles((x, nme) -> nme.endsWith(ext));
        if (fs != null) Collections.addAll(out, fs);
        Collections.sort(out);
        return out;
    }

    private static String exec(int timeoutSec, File dir, String... cmd) throws Exception {
        File f = File.createTempFile("out", ".txt");
        try {
            ProcessBuilder pb = new ProcessBuilder(cmd).redirectErrorStream(true).redirectOutput(f);
            Process p = pb.start();
            if (!p.waitFor(timeoutSec, TimeUnit.SECONDS)) p.destroyForcibly();
            return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8);
        } finally { f.delete(); }
    }
}
